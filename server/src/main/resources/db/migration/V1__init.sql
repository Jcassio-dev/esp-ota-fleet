create table device (
    id              varchar(64) primary key,
    current_version varchar(32) not null,
    battery         integer,
    last_seen_at    timestamp with time zone not null,
    created_at      timestamp with time zone not null
);

create table release (
    id              bigint generated by default as identity primary key,
    version         varchar(32)  not null unique,
    project_name    varchar(32)  not null,
    size_bytes      bigint       not null,
    sha256          varchar(64)  not null,
    signature       text         not null,
    storage_path    varchar(512) not null,
    rollout_percent integer      not null,
    status          varchar(16)  not null,
    pause_reason    varchar(500),
    created_at      timestamp with time zone not null
);

create table update_attempt (
    id            bigint generated by default as identity primary key,
    device_id     varchar(64) not null references device (id),
    release_id    bigint      not null references release (id),
    state         varchar(16) not null,
    failure_count integer     not null,
    detail        varchar(500),
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null,
    version       bigint      not null,
    constraint uq_attempt_device_release unique (device_id, release_id)
);

create index idx_attempt_release_state on update_attempt (release_id, state);
